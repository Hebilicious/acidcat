import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, relative } from "node:path";

import { CLI_EXIT_CODES, CLI_RESERVED_FLAGS, CLI_RESUME_FLAGS } from "@acid-cat/spec-ts";

const MODEL = join(import.meta.dirname, "..");
const ROOT = join(MODEL, "..");
const COMMAND = "moon run model:generate";
const HEADER = `Generated by \`${COMMAND}\` from model/cli-output.qnt. Do not edit.`;

type Form = "human" | "json";
type Flag = { readonly names: readonly string[]; readonly form: Form } | { readonly names: readonly string[]; readonly values: readonly (readonly [string, Form])[] };

const isRecord = (value: unknown): value is { readonly [key: string]: unknown } => typeof value === "object" && value !== null && !Array.isArray(value);

const field = (value: unknown, key: string): unknown => {
  if (!isRecord(value) || !Object.hasOwn(value, key)) throw new Error(`The ITF value has no field ${key}: ${JSON.stringify(value)}`);
  return value[key];
};

const list = (value: unknown): readonly unknown[] => {
  if (!Array.isArray(value)) throw new Error(`The ITF value is not a list: ${JSON.stringify(value)}`);
  return value;
};

const string = (value: unknown): string => {
  if (typeof value !== "string") throw new Error(`The ITF value is not a string: ${JSON.stringify(value)}`);
  return value;
};

const boolean = (value: unknown): boolean => {
  if (typeof value !== "boolean") throw new Error(`The ITF value is not a boolean: ${JSON.stringify(value)}`);
  return value;
};

const integer = (value: unknown): number => {
  const digits = string(field(value, "#bigint"));
  if (!/^-?\d+$/.test(digits)) throw new Error(`The ITF value is not an integer: ${JSON.stringify(value)}`);
  return Number(digits);
};

const CHARACTERS: { readonly [name: string]: string } = {
  "<TAB>": "\t",
  "<LF>": "\n",
  "<VT>": "\u000B",
  "<FF>": "\f",
  "<CR>": "\r",
  "<NEL>": "\u0085",
  "<BOM>": "﻿",
};

const piece = (value: unknown): string => {
  const text = string(value);
  if (!/^<[A-Z]+>$/.test(text)) return text;
  const character = CHARACTERS[text];
  if (character === undefined) throw new Error(`${text} is not a character that the generator knows.`);
  return character;
};

const text = (value: unknown): string => list(value).map(piece).join("");

const pair = (value: unknown): readonly [unknown, unknown] => {
  const items = list(field(value, "#tup"));
  const [first, second] = items;
  if (items.length !== 2) throw new Error(`The ITF value is not a pair: ${JSON.stringify(value)}`);
  return [first, second];
};

const variant = (value: unknown, tags: readonly string[]): { readonly tag: string; readonly value: unknown } => {
  const tag = string(field(value, "tag"));
  if (!tags.includes(tag)) throw new Error(`${tag} is not one of ${tags.join(", ")}.`);
  return { tag, value: field(value, "value") };
};

const form = (value: unknown): Form => (variant(value, ["Human", "Json"]).tag === "Human" ? "human" : "json");

const flag = (value: unknown): Flag => {
  const names = list(field(value, "names")).map(text);
  const kind = variant(field(value, "kind"), ["Switch", "Values"]);
  if (kind.tag === "Switch") return { names, form: form(kind.value) };
  return { names, values: list(kind.value).map(pair).map(([name, chosen]) => [text(name), form(chosen)] as const) };
};

const env = (value: unknown): { readonly [name: string]: string } =>
  Object.fromEntries(list(field(value, "#map")).map((entry) => {
    const items = list(entry);
    const [name, setting] = items;
    if (items.length !== 2) throw new Error(`The ITF value is not an entry of a map: ${JSON.stringify(entry)}`);
    return [string(name), text(setting)];
  }));

const named = (value: unknown): readonly [string, string] => {
  const [name, what] = pair(value);
  return [text(name), string(what)];
};

function chosen(value: unknown): Form | null {
  const { tag, value: byFlag } = variant(value, ["ByDefault", "ByFlag"]);
  return tag === "ByFlag" ? form(byFlag) : null;
}

function outcome(value: unknown, message: string): { readonly form: Form | null; readonly rest: readonly string[] } | { readonly error: string } {
  const { tag, value: detail } = variant(value, ["Parsed", "BadValue"]);
  if (tag === "BadValue") return { error: message };
  return { form: chosen(field(detail, "chosen")), rest: list(field(detail, "rest")).map(text) };
}

function run(value: unknown, message: string): { readonly form: Form; readonly rest: readonly string[] } | { readonly exitCode: number; readonly error: string } {
  const { tag, value: detail } = variant(value, ["Proceeds", "Stops"]);
  if (tag === "Stops") return { exitCode: integer(field(detail, "exitCode")), error: message };
  return { form: form(field(detail, "form")), rest: list(field(detail, "rest")).map(text) };
}

const fallback = (value: unknown): "auto" | "json" => (variant(value, ["AutoDefault", "JsonDefault"]).tag === "AutoDefault" ? "auto" : "json");

function modelState(): unknown {
  const directory = mkdtempSync(join(tmpdir(), "acid-cat-model-"));
  try {
    const itf = join(directory, "cases.itf.json");
    execFileSync(
      join(MODEL, "node_modules", ".bin", "quint"),
      ["run", "cli-output-cases.qnt", "--main=cliOutputCases", "--max-steps=0", "--max-samples=1", `--out-itf=${itf}`, "--verbosity=0"],
      { cwd: MODEL, stdio: ["ignore", "ignore", "inherit"] },
    );
    const parsed: unknown = JSON.parse(readFileSync(itf, "utf8"));
    const [state] = list(field(parsed, "states"));
    return state;
  } finally {
    rmSync(directory, { recursive: true, force: true });
  }
}

const MESSAGE_KEYS = ["noName", "badName", "sameAsOutputFlag", "sameAsOther", "noValues", "badValue", "switchHelp", "valuesHelp", "meaning"] as const;

const state = modelState();
const data = field(state, "data");
const ciVariable = string(field(data, "ciVariable"));
const agentVariables = list(field(data, "agentVariables")).map(string);
const falseValues = list(field(data, "falseValues")).map(text);
const trimCharacters = list(field(data, "trimCharacters")).map(piece);
const programFlags = list(field(data, "programFlags")).map(text);
const resumeFlags = list(field(data, "resumeFlags")).map(text);
const reservedFlags = list(field(data, "reservedFlags")).map(named);
const exitCode = integer(field(data, "invalidInputExitCode"));
const messages = MESSAGE_KEYS.map((key) => [key, text(field(field(data, "messages"), key))] as const);
const formNames = { human: text(field(field(data, "formNames"), "human")), json: text(field(field(data, "formNames"), "json")) };
const listWords = field(data, "list");
const separators = [
  ["LIST_SEPARATOR", text(field(listWords, "separator"))],
  ["OR_WORD", text(field(listWords, "orWord"))],
  ["AND_WORD", text(field(listWords, "andWord"))],
  ["NAME_SEPARATOR", text(field(listWords, "names"))],
  ["VALUE_SEPARATOR", text(field(listWords, "values"))],
] as const;

const sameList = (left: readonly string[], right: readonly string[]): boolean => left.length === right.length && left.every((each, index) => each === right[index]);
if (!sameList(resumeFlags, CLI_RESUME_FLAGS.map((name) => `--${name}`))) throw new Error("The resume flags of the model are not the flags of watch in @acid-cat/spec-ts.");
if (!sameList(programFlags, CLI_RESERVED_FLAGS)) throw new Error("The program flags of the model are not CLI_RESERVED_FLAGS of @acid-cat/spec-ts.");
if (!sameList(reservedFlags.map(([name]) => name), [...programFlags, ...resumeFlags])) throw new Error("The reserved flags of the model are not the program flags and the resume flags.");
if (exitCode !== CLI_EXIT_CODES["invalid-input"]) throw new Error("The exit code of the model is not the exit code of invalid-input in @acid-cat/spec-ts.");

const problemCases = list(field(state, "problemCases"));
const [firstProblem] = problemCases;
const choiceCases = list(field(state, "choiceCases"));
const [firstChoice] = choiceCases;

const cases = {
  auto: list(field(state, "autoCases")).map((each) => ({ isTerminal: boolean(field(each, "isTerminal")), env: env(field(each, "env")), form: form(field(each, "form")) })),
  problems: {
    others: list(field(firstProblem, "others")).map(named),
    cases: problemCases.map((each) => ({ flags: list(field(each, "flags")).map(flag), messages: list(field(each, "problems")).map(text) })),
  },
  choices: {
    flags: list(field(firstChoice, "flags")).map(flag),
    cases: choiceCases.map((each) => ({
      args: list(field(each, "args")).map(text),
      commands: list(field(each, "commands")).map(text),
      ...outcome(field(each, "outcome"), text(field(each, "message"))),
    })),
  },
  decisions: {
    flags: list(field(firstChoice, "flags")).map(flag),
    cases: list(field(state, "decideCases")).map((each) => ({
      default: fallback(field(each, "fallback")),
      isTerminal: boolean(field(each, "isTerminal")),
      env: env(field(each, "env")),
      args: list(field(each, "args")).map(text),
      ...run(field(each, "result"), text(field(each, "message"))),
    })),
  },
  help: list(field(state, "helpCases")).map((each) => ({ flag: flag(field(each, "flag")), line: text(field(each, "line")) })),
};

const asciiJson = (value: unknown): string =>
  JSON.stringify(value).replaceAll(/[^\u0020-\u007E]/g, (character) => `\\u${(character.codePointAt(0) ?? 0).toString(16).padStart(4, "0")}`);

const casesJson = `{\n${Object.entries(cases)
  .map(([key, value]) => {
    if (Array.isArray(value)) return `  ${JSON.stringify(key)}: [\n${value.map((each) => `    ${asciiJson(each)}`).join(",\n")}\n  ]`;
    const members = Object.entries(value).map(([member, items]) =>
      Array.isArray(items) && member === "cases"
        ? `    "cases": [\n${items.map((each) => `      ${asciiJson(each)}`).join(",\n")}\n    ]`
        : `    ${JSON.stringify(member)}: ${asciiJson(items)}`,
    );
    return `  ${JSON.stringify(key)}: {\n${members.join(",\n")}\n  }`;
  })
  .join(",\n")}\n}\n`;

const typescriptList = (name: string, items: readonly string[]): string => `export const ${name}: readonly string[] = [${items.map((item) => JSON.stringify(item)).join(", ")}];`;

const typescript = [
  `// ${HEADER}`,
  "",
  `export const CI_VARIABLE = ${JSON.stringify(ciVariable)};`,
  "",
  "export const AGENT_VARIABLES: readonly string[] = [",
  ...agentVariables.map((name) => `  ${JSON.stringify(name)},`),
  "];",
  "",
  typescriptList("FALSE_VALUES", falseValues),
  "",
  `export const TRIM_CHARACTERS = ${JSON.stringify(trimCharacters.join(""))};`,
  "",
  typescriptList("PROGRAM_FLAGS", programFlags),
  "",
  typescriptList("RESUME_FLAGS", resumeFlags),
  "",
  "export const RESERVED_FLAGS: readonly (readonly [name: string, description: string])[] = [",
  ...reservedFlags.map(([name, what]) => `  [${JSON.stringify(name)}, ${JSON.stringify(what)}],`),
  "];",
  "",
  `export const INVALID_INPUT_EXIT_CODE = ${exitCode};`,
  "",
  "export const MESSAGES = {",
  ...messages.map(([key, template]) => `  ${key}: ${JSON.stringify(template)},`),
  "} as const;",
  "",
  `export const FORM_NAMES = { human: ${JSON.stringify(formNames.human)}, json: ${JSON.stringify(formNames.json)} } as const;`,
  "",
  ...separators.map(([name, value]) => `export const ${name} = ${JSON.stringify(value)};`),
  "",
].join("\n");

const rustEscape = (value: string, quote: string): string =>
  Array.from(value, (character) => {
    const code = character.codePointAt(0) ?? 0;
    if (character === "\\" || character === quote) return `\\${character}`;
    return code >= 0x20 && code < 0x7f ? character : `\\u{${code.toString(16)}}`;
  }).join("");

const rustString = (value: string): string => `"${rustEscape(value, '"')}"`;
const rustChar = (value: string): string => `'${rustEscape(value, "'")}'`;
const RUSTFMT_WIDTH = 100;
const rustConst = (name: string, type: string, value: string): string => {
  const line = `pub(crate) const ${name}: ${type} = ${value};`;
  return line.length <= RUSTFMT_WIDTH ? line : `pub(crate) const ${name}: ${type} =\n    ${value};`;
};
const rustList = (name: string, items: readonly string[]): string => rustConst(name, `[&str; ${items.length}]`, `[${items.map(rustString).join(", ")}]`);
const snake = (key: string): string => key.replaceAll(/[A-Z]/g, (letter) => `_${letter.toLowerCase()}`).toUpperCase();

const rust = [
  `// ${HEADER}`,
  "",
  rustConst("CI_VARIABLE", "&str", rustString(ciVariable)),
  "",
  `pub(crate) const AGENT_VARIABLES: [&str; ${agentVariables.length}] = [`,
  ...agentVariables.map((name) => `    ${rustString(name)},`),
  "];",
  "",
  rustList("FALSE_VALUES", falseValues),
  "",
  rustConst("TRIM_CHARACTERS", `[char; ${trimCharacters.length}]`, `[${trimCharacters.map(rustChar).join(", ")}]`),
  "",
  rustList("PROGRAM_FLAGS", programFlags),
  "",
  rustList("RESUME_FLAGS", resumeFlags),
  "",
  `pub(crate) const RESERVED_FLAGS: [(&str, &str); ${reservedFlags.length}] = [`,
  ...reservedFlags.map(([name, what]) => `    (${rustString(name)}, ${rustString(what)}),`),
  "];",
  "",
  rustConst("INVALID_INPUT_EXIT_CODE", "i32", String(exitCode)),
  "",
  ...messages.map(([key, template]) => rustConst(`${snake(key)}_MESSAGE`, "&str", rustString(template))),
  "",
  rustConst("HUMAN_FORM_NAME", "&str", rustString(formNames.human)),
  rustConst("JSON_FORM_NAME", "&str", rustString(formNames.json)),
  "",
  ...separators.map(([name, value]) => rustConst(name, "&str", rustString(value))),
  "",
].join("\n");

const outputs: readonly (readonly [string, string])[] = [
  ["packages/core-ts/src/cli-output.generated.ts", typescript],
  ["packages/core-effect/src/internal/output.generated.ts", typescript],
  ["packages/core-rust/src/cli/output_generated.rs", rust],
  ["packages/core-ts/test/fixtures/cli-output-cases.json", casesJson],
  ["packages/core-effect/test/fixtures/cli-output-cases.json", casesJson],
  ["packages/core-rust/tests/fixtures/cli_output_cases.json", casesJson],
];

const read = (path: string): string | undefined => {
  try {
    return readFileSync(path, "utf8");
  } catch {
    return undefined;
  }
};

const check = process.argv.includes("--check");
const stale: string[] = [];
for (const [path, content] of outputs) {
  const target = join(ROOT, path);
  if (read(target) === content) continue;
  if (check) stale.push(relative(ROOT, target));
  else writeFileSync(target, content);
}
if (stale.length > 0) {
  console.error(`These files are not the output of the model. Run \`${COMMAND}\`, and do not edit them by hand:\n${stale.map((path) => `  ${path}`).join("\n")}`);
  process.exitCode = 1;
}
